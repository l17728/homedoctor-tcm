async def seed(db_path: str) -> dict[str, Any]:
    """Insert expanded therapy entities. Returns stats dict."""
    db_dir = os.path.dirname(db_path)
    if db_dir:
        os.makedirs(db_dir, exist_ok=True)

    inserted = 0
    skipped = 0
    errors = 0
    error_details: list[str] = []

    async with aiosqlite.connect(db_path) as db:
        db.row_factory = aiosqlite.Row
        await db.execute(_CREATE_TABLE)
        await db.commit()

        before_row = await (
            await db.execute(
                "SELECT COUNT(*) AS cnt FROM knowledge_entities WHERE entity_type = 'therapy'"
            )
        ).fetchone()
        before_count = before_row[0] if before_row else 0

        for entry in ALL_THERAPIES:
            try:
                # Title-existence check — never overwrite an existing entry.
                title = entry["title"]
                existing = await (
                    await db.execute(
                        "SELECT id FROM knowledge_entities WHERE title = ?", (title,)
                    )
                ).fetchone()

                if existing:
                    skipped += 1
                    continue

                now = datetime.now(CST).strftime("%Y-%m-%d %H:%M:%S")
                await db.execute(
                    _INSERT_SQL,
                    (
                        entry["id"],
                        entry["entity_type"],
                        entry["source_table"],
                        entry["source_id"],
                        entry["title"],
                        entry["summary"],
                        entry["keywords"],
                        entry["tags"],
                        entry["category"],
                        entry["content_preview"],
                        entry["properties"],
                        entry["source_type"],
                        entry["status"],
                        now,
                        now,
                    ),
                )
                inserted += 1
            except Exception as exc:  # noqa: BLE001 — per-entry isolation
                errors += 1
                error_details.append(f"{entry.get('title', 'unknown')}: {exc}")

        await db.commit()

        after_row = await (
            await db.execute(
                "SELECT COUNT(*) AS cnt FROM knowledge_entities WHERE entity_type = 'therapy'"
            )
        ).fetchone()
        after_count = after_row[0] if after_row else 0

        cat_cursor = await db.execute(
            """SELECT category, COUNT(*) AS cnt
               FROM knowledge_entities
               WHERE entity_type = 'therapy'
               GROUP BY category ORDER BY category"""
        )
        cat_rows = await cat_cursor.fetchall()
        category_breakdown = {row[0]: row[1] for row in cat_rows}

    stats = {
        "before": before_count,
        "after": after_count,
        "inserted": inserted,
        "skipped": skipped,
        "errors": errors,
        "total_new_entries": len(ALL_THERAPIES),
        "categories": category_breakdown,
    }

    print("=" * 60)
    print("  外治理疗扩展种子 (seed_therapies_expanded)")
    print("=" * 60)
    print(f"  待插入条目: {stats['total_new_entries']}")
    print(f"  新增成功:   {stats['inserted']}")
    print(f"  跳过(已存在): {stats['skipped']}")
    print(f"  错误:       {stats['errors']}")
    print(f"  理疗实体总数: {stats['before']} → {stats['after']}")
    print()
    print("  分类统计 (therapy):")
    for cat, cnt in sorted(stats["categories"].items(), key=lambda x: -x[1]):
        print(f"    {cat}: {cnt}")

    if error_details:
        print()
        print("  错误详情:")
        for d in error_details:
            print(f"    - {d}")

    print("=" * 60)
    if errors:
        print(f"  ⚠ 完成（{errors} 个错误）")
    else:
        print(f"  ✓ 完成 — 新增 {inserted} 条理疗实体")
    print("=" * 60)

    return stats


if __name__ == "__main__":
    db_path = os.environ.get("HOMEDOCTOR_DATABASE_URL", "data/homedoctor.db")
    if len(sys.argv) > 1:
        if sys.argv[1] in ("--db", "-d"):
            db_path = sys.argv[2]
        else:
            db_path = sys.argv[1]
    asyncio.run(seed(db_path))
