def _entry(
    eid: str,
    title: str,
    summary: str,
    category: str,
    content_preview: str,
    indications: list[str],
    technique: str,
    frequency: str,
    duration: str,
    caution: str,
    best_for: str,
    difficulty: str,
) -> dict[str, Any]:
    """Build a therapy entity dict with standardised keys."""
    properties = {
        "indications": indications,
        "technique": technique,
        "frequency": frequency,
        "duration": duration,
        "caution": caution,
        "best_for": best_for,
        "difficulty": difficulty,
    }
    keywords = [difficulty, category, best_for]
    return {
        "id": eid,
        "entity_type": "therapy",
        "source_table": "therapies",
        "source_id": eid,
        "title": title,
        "summary": summary,
        "keywords": json.dumps(keywords, ensure_ascii=False),
        "tags": json.dumps([category], ensure_ascii=False),
        "category": category,
        "content_preview": content_preview,
        "properties": json.dumps(properties, ensure_ascii=False),
        "source_type": "system",
        "status": "active",
    }


