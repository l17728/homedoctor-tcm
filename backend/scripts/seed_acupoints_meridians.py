async def seed_meridians(db) -> int:
    """Insert 14 meridian entities. Returns count inserted."""
    now = _now()
    count = 0
    for m in MERIDIANS:
        code = m["properties"]["code"]
        await db.execute(
            _INSERT_ENTITY,
            (
                m["id"],
                "meridian",
                "meridian",
                f"meridian:{code}",
                m["title"],
                m["summary"],
                json.dumps([m["properties"]["organ"]], ensure_ascii=False),
                json.dumps([m["category"]], ensure_ascii=False),
                m["category"],
                m["properties"]["common_indications"][:200],
                json.dumps(m["properties"], ensure_ascii=False),
                "system",
                "active",
                now,
                now,
            ),
        )
        count += 1
    return count


async def seed_acupoints(db) -> tuple[int, dict[str, str]]:
    """Insert acupoint entities. Returns (count, {code: entity_id})."""
    now = _now()
    acupoints = build_acupoints()
    code_to_id: dict[str, str] = {}
    count = 0
    for ap in acupoints:
        code = ap["properties"]["code"]
        entity_id = ap["id"]
        code_to_id[code] = entity_id
        await db.execute(
            _INSERT_ENTITY,
            (
                entity_id,
                "acupoint",
                "acupoint",
                f"acupoint:{code}",
                ap["title"],
                ap["summary"],
                json.dumps(ap["properties"].get("functions", []), ensure_ascii=False),
                json.dumps([ap["properties"].get("specific_point", "")], ensure_ascii=False) if ap["properties"].get("specific_point") else "[]",
                ap["category"],
                "；".join(ap["properties"].get("indications", []))[:200],
                json.dumps(ap["properties"], ensure_ascii=False),
                "system",
                "active",
                now,
                now,
            ),
        )
        count += 1
    return count, code_to_id


async def seed_belongs_to_meridian_relationships(
    db, code_to_id: dict[str, str]
) -> int:
    """Create belongs_to_meridian relationships: each acupoint -> its meridian."""
    now = _now()
    count = 0
    for code, acupoint_id in code_to_id.items():
        meridian_code = code.rstrip("0123456789")
        meridian_id = f"meridian-{meridian_code}"
        rel_id = f"rel:btm:{acupoint_id}->{meridian_id}"
        await db.execute(
            _INSERT_REL,
            (
                rel_id,
                acupoint_id,
                meridian_id,
                "belongs_to_meridian",
                json.dumps({"meridian": _MERIDIAN_NAMES[meridian_code]}, ensure_ascii=False),
                1.0,
                now,
            ),
        )
        count += 1
    return count


async def seed_treats_relationships(
    db, code_to_id: dict[str, str]
) -> tuple[int, int]:
    """Create treats relationships: acupoint -> symptom (only for existing symptoms).

    Queries knowledge_entities for entity_type='symptom' and matches acupoint
    indications by title. Returns (relationships_created, symptoms_matched).
    """
    now = _now()

    # Build symptom title -> entity_id lookup
    symptom_rows = await db.query(
        "SELECT id, title FROM knowledge_entities WHERE entity_type = 'symptom' AND status = 'active'"
    )
    symptom_map: dict[str, str] = {}
    for row in symptom_rows:
        title = (row.get("title") or "").strip()
        if title:
            symptom_map[title] = row["id"]

    if not symptom_map:
        return 0, 0

    rel_count = 0
    matched_symptoms = 0
    acupoints = build_acupoints()

    for ap in acupoints:
        code = ap["properties"]["code"]
        acupoint_id = code_to_id.get(code)
        if not acupoint_id:
            continue

        indications = ap["properties"].get("indications", [])
        for indication in indications:
            indication = indication.strip()
            symptom_id = symptom_map.get(indication)
            if not symptom_id:
                continue

            rel_id = f"rel:treats:{acupoint_id}->{symptom_id}"
            await db.execute(
                _INSERT_REL,
                (
                    rel_id,
                    acupoint_id,
                    symptom_id,
                    "treats",
                    json.dumps(
                        {"indication": indication, "source": "acupoint"},
                        ensure_ascii=False,
                    ),
                    1.0,
                    now,
                ),
            )
            rel_count += 1

    return rel_count, len(symptom_map)


