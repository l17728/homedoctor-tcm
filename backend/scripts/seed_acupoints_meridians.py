def build_acupoints() -> list[dict]:
    """Expand compact tuples into full acupoint dicts matching the schema."""
    result = []
    for (code, name, summary, location, needling, moxibustion,
         functions, indications, combinations, specific_point, caution) in ACUPOINT_DATA:
        meridian_code = code.rstrip("0123456789")
        meridian_name = _MERIDIAN_NAMES[meridian_code]
        props: dict = {
            "code": code,
            "meridian": meridian_name,
            "meridian_code": meridian_code,
            "location": location,
            "needling": needling,
            "moxibustion": moxibustion,
            "functions": functions,
            "indications": indications,
            "combinations": combinations,
            "specific_point": specific_point,
        }
        if caution:
            props["caution"] = caution
        result.append({
            "id": f"acupoint-{code}",
            "title": name,
            "summary": summary,
            "category": meridian_name,
            "properties": props,
        })
    return result

