INSERT_SQL = """INSERT OR IGNORE INTO herbs
    (id, name, aliases, nature, flavor, meridians, efficacy, indications,
     contraindications, dosage_min_g, dosage_max_g, toxicity, category,
     processing_method, origin, source_ref, properties)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)"""


def seed() -> None:
    db_url = os.environ.get("DATABASE_URL", "sqlite:///data/family-doctor.db")
    db_path = db_url.replace("sqlite:///", "").replace("sqlite://", "")

    # Ensure parent directory exists
    db_dir = os.path.dirname(db_path)
    if db_dir:
        os.makedirs(db_dir, exist_ok=True)

    conn = sqlite3.connect(db_path)
    conn.execute(HERBS_DDL)

    inserted = 0
    for h in HERBS:
        params = (
            h["id"], h["name"], h.get("aliases"), h.get("nature"), h.get("flavor"),
            h.get("meridians"), h.get("efficacy"), h.get("indications"),
            h.get("contraindications"), h.get("dosage_min_g"), h.get("dosage_max_g"),
            h.get("toxicity"), h.get("category"), h.get("processing_method"),
            h.get("origin"), h.get("source_ref"), h.get("properties"),
        )
        cursor = conn.execute(INSERT_SQL, params)
        if cursor.rowcount > 0:
            inserted += 1

    conn.commit()
    print(f"Seeded {inserted} new herbs ({len(HERBS)} total in batch, rest already existed)")

    count = conn.execute("SELECT COUNT(*) FROM herbs").fetchone()[0]
    print(f"Total herbs in DB: {count}")

    # Print category breakdown
    rows = conn.execute(
        "SELECT category, COUNT(*) as cnt FROM herbs GROUP BY category ORDER BY cnt DESC"
    ).fetchall()
    print("\nCategory breakdown:")
    for cat, cnt in rows:
        print(f"  {cat}: {cnt}")

    conn.close()


if __name__ == "__main__":
    seed()
