def seed(db_path: str) -> None:
    """Insert herbs into the database using synchronous sqlite3."""
    conn = sqlite3.connect(db_path)
    conn.execute("PRAGMA journal_mode=WAL")
    cur = conn.cursor()

    inserted = 0
    for h in HERBS:
        cur.execute(
            """INSERT OR IGNORE INTO herbs
               (id, name, aliases, nature, flavor, meridians, efficacy, indications,
                contraindications, dosage_min_g, dosage_max_g, toxicity, category, properties)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (
                h["id"], h["name"], h["aliases"], h["nature"], h["flavor"],
                h["meridians"], h["efficacy"], h["indications"],
                h["contraindications"], h["dosage_min_g"], h["dosage_max_g"],
                h["toxicity"], h["category"], h["properties"],
            ),
        )
        if cur.rowcount > 0:
            inserted += 1

    conn.commit()

    # --- verify ---
    total = cur.execute("SELECT COUNT(*) FROM herbs").fetchone()[0]
    conn.close()

    print(f"Seeded {inserted} herbs (batch 2)")
    print(f"Total herbs in database: {total}")


def main() -> None:
    db_path = sys.argv[2] if "--db" in sys.argv else DEFAULT_DB
    if not Path(db_path).exists():
        print(f"Error: database not found at {db_path}", file=sys.stderr)
        sys.exit(1)
    seed(db_path)


if __name__ == "__main__":
    main()
