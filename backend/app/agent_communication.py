async def agent_message(
    db: DbAdapter,
    from_agent: str,
    to_agent: str,
    content: str,
    message_type: str = "message",
    reply_to: str | None = None,
    metadata: dict[str, Any] | None = None,
) -> str:
    """Send a message from one agent to another. Returns message ID."""
    mid = f"conv-{uuid.uuid4()}"
    await db.execute(
        """INSERT INTO agent_conversations
           (id, from_agent, to_agent, message_type, content, reply_to, metadata)
           VALUES (?, ?, ?, ?, ?, ?, ?)""",
        (
            mid, from_agent, to_agent, message_type,
            content, reply_to,
            json.dumps(metadata or {}, ensure_ascii=False),
        ),
    )
    logger.info("agent_comm: %s→%s [%s]: %s...", from_agent, to_agent, message_type, content[:50])
    return mid


async def agent_ask(
    db: DbAdapter,
    from_agent: str,
    to_agent: str,
    question: str,
) -> dict[str, Any]:
    """Ask a question and generate a response using LLM.

    The response is generated by looking at the other agent's memories
    and the knowledge base, then saved as a reply.
    """
    from app.llm_unified import llm_chat
    from app.agent_memory import memory_search

    other_memories = await memory_search(db, to_agent, question, limit=5)

    context = ""
    if other_memories:
        context = "\n相关记忆：\n" + "\n".join(
            f"- [{m['memory_type']}] {m['content'][:80]}" for m in other_memories
        )

    prompt = f"""你是{to_agent}。{from_agent}向你提问：

问题：{question}
{context}

请基于你的角色和经验回答。简洁直接，2-3句话。"""

    reply = await llm_chat(db, [{"role": "user", "content": prompt}])

    reply_id = await agent_message(
        db, to_agent, from_agent, reply,
        message_type="reply",
        metadata={"question": question},
    )

    return {
        "question_id": await agent_message(db, from_agent, to_agent, question, "ask"),
        "reply_id": reply_id,
        "reply": reply,
    }


async def agent_propose(
    db: DbAdapter,
    from_agent: str,
    to_agent: str,
    proposal: str,
    context: dict[str, Any] | None = None,
) -> str:
    """Make a proposal to another agent."""
    return await agent_message(
        db, from_agent, to_agent, proposal,
        message_type="propose",
        metadata=context,
    )


_CONFIG_PATTERNS = [
    re.compile(r'建议将\s*(\w+)[的.]\s*(\w+)\s*设置为\s*(.+?)[\s。，；;,]\s*'),
    re.compile(r'config:\s*(\w+)\.(\w+)\s*=\s*(.+?)[\s\n;,；；]'),
]


async def auto_apply_debate_results(db: DbAdapter, summary_text: Any) -> list[dict[str, Any]]:
    """Parse debate summary for config-change suggestions and apply them.

    Recognizes patterns like:
        建议将knowledge_agent的temperature设置为0.5
        config: patrol_agent.gap_threshold = 3
    """
    from app.agent_tools import tool_set_config

    applied: list[dict[str, Any]] = []

    if isinstance(summary_text, dict):
        action_items = summary_text.get("action_items", [])
        search_text = "\n".join(str(item) for item in action_items)
    else:
        search_text = str(summary_text or "")

    if not search_text.strip():
        return applied

    for pattern in _CONFIG_PATTERNS:
        for match in pattern.finditer(search_text):
            agent_name, key, raw_value = (
                match.group(1), match.group(2), match.group(3).strip(),
            )
            try:
                value: Any = json.loads(raw_value)
            except (json.JSONDecodeError, ValueError):
                value = raw_value
            try:
                result = await tool_set_config(db, agent_name, key, value)
                applied.append(result)
                logger.info("auto_apply_debate: %s.%s = %s", agent_name, key, value)
            except Exception as exc:
                logger.warning("auto_apply_debate: failed %s.%s=%s: %s", agent_name, key, value, exc)

    return applied


async def agent_debate(
    db: DbAdapter,
    from_agent: str,
    to_agent: str,
    topic: str,
    rounds: int = 2,
) -> list[dict[str, Any]]:
    """Initiate a multi-round debate on a topic."""
    from app.llm_unified import llm_chat

    messages: list[dict[str, Any]] = []
    current_topic = topic

    for i in range(rounds):
        for speaker, listener in [(from_agent, to_agent), (to_agent, from_agent)]:
            from app.agent_memory import memory_search
            memories = await memory_search(db, speaker, current_topic, limit=3)

            prompt = f"""你是{speaker}。正在与{listener}讨论：

话题：{current_topic}
你的相关记忆：{json.dumps([m['content'][:60] for m in memories], ensure_ascii=False)}

请表达你的观点（2-3句话）。要有建设性，可以质疑对方，但要有依据。"""

            reply = await llm_chat(db, [{"role": "user", "content": prompt}])
            mid = await agent_message(
                db, speaker, listener, reply,
                message_type="debate",
                metadata={"topic": topic, "round": i + 1},
            )
            messages.append({
                "id": mid,
                "from": speaker,
                "content": reply,
                "round": i + 1,
            })
            current_topic = reply[:200]

    summary_prompt = f"""以下是关于「{topic}」的讨论记录，请总结共识和分歧：

{json.dumps([{'from': m['from'], 'content': m['content']} for m in messages], ensure_ascii=False)}

返回JSON：{{"consensus": "...", "disagreements": [...], "action_items": [...]}}"""

    from app.json_extractor import extract_json
    summary_reply = await llm_chat(db, [{"role": "user", "content": summary_prompt}])
    summary = extract_json(summary_reply)

    from app.agent_memory import memory_save
    if isinstance(summary, dict):
        await memory_save(
            db, SHARED,
            f"辩论总结[{topic}]：共识={summary.get('consensus', '')}",
            memory_type="experience",
            confidence=0.7,
        )

    try:
        applied = await auto_apply_debate_results(db, summary)
        if applied:
            logger.info("agent_debate: auto-applied %d config changes", len(applied))
    except Exception as exc:
        logger.warning("agent_debate: auto-apply failed: %s", exc)

    return messages


async def get_conversation_history(
    db: DbAdapter,
    agent_name: str | None = None,
    limit: int = 20,
) -> list[dict[str, Any]]:
    """Get conversation history."""
    if agent_name:
        rows = await db.query(
            """SELECT * FROM agent_conversations
               WHERE from_agent = ? OR to_agent = ?
               ORDER BY created_at DESC LIMIT ?""",
            (agent_name, agent_name, limit),
        )
    else:
        rows = await db.query(
            "SELECT * FROM agent_conversations ORDER BY created_at DESC LIMIT ?",
            (limit,),
        )
    return [_format_conversation(r) for r in rows]


def _format_conversation(row: dict[str, Any]) -> dict[str, Any]:
    metadata = row.get("metadata")
    if isinstance(metadata, str):
        try:
            metadata = json.loads(metadata)
        except (json.JSONDecodeError, TypeError):
            metadata = {}
    return {
        "id": row.get("id", ""),
        "from_agent": row.get("from_agent", ""),
        "to_agent": row.get("to_agent", ""),
        "message_type": row.get("message_type", ""),
        "content": row.get("content", ""),
        "reply_to": row.get("reply_to"),
        "metadata": metadata if isinstance(metadata, dict) else {},
        "created_at": row.get("created_at", ""),
    }
